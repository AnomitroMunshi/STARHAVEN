// Regenerates NAMES_USED.md from the wiki cards, Atlas keepers and unit_commanders.md.
// Run from the repo root: node tools/names_used.js
// Everything under "## Story-only names" in the existing file is kept as written.
const fs = require('fs');
const OUT = 'NAMES_USED.md';
const wiki = fs.readFileSync('starhaven_wiki.html', 'utf8');
const names = new Map(); // full name -> set of sources

const add = (n, src) => {
  n = n.replace(/\s*\(.*$/, '').trim();
  // strip ranks, including hyphenated ones like Aerie-Captain or Admiral-King
  while (/^(Order Master|[A-Z][a-z]+-[A-Z][a-z]+|Captain|General|King|Queen|Prince|Princess|Sultan|Sultana|Director|Commander|Marshal|Admiral|Lord|Lady|Sir|Dame|Elder|Chief|Warden)\s/.test(n)) n = n.replace(/^(Order Master|\S+)\s+/, '');
  if (!/^[A-ZÀ-Ý]/.test(n) || n.length < 3 || /^(—|none|The )/.test(n)) return;
  if (!names.has(n)) names.set(n, new Set());
  names.get(n).add(src);
};

// character cards (CHARACTERS and DUMMY_LEGENDS): a name followed closely by a title
for (const m of wiki.matchAll(/id:\s*'([^']+)',\s*name:\s*['"]([^'"]+)['"][\s\S]{0,3000}?category:\s*'([^']+)'/g)) add(m[2], 'card: ' + m[3]);
// Atlas place keepers: "Name, role"
for (const m of wiki.matchAll(/keeper:'([^',]+)/g)) add(m[1], 'Atlas keeper');
// unit commanders without cards
for (const line of fs.readFileSync('unit_commanders.md', 'utf8').split('\n')) {
  const cols = line.split('|').map(s => s.trim());
  if (cols.length >= 4 && cols[2] && !/^(-+|Commander)/.test(cols[2])) cols[2].split(/·|,|\//).forEach(n => add(n.replace(/\*/g, ''), 'unit commander'));
}

const keep = fs.existsSync(OUT) ? (fs.readFileSync(OUT, 'utf8').split('## Story-only names')[1] || '') : '\n\n';
const byFirst = new Map();
for (const n of names.keys()) { const f = n.split(' ')[0]; byFirst.set(f, (byFirst.get(f) || []).concat(n)); }
const rows = [...names.keys()].sort((a, b) => a.localeCompare(b)).map(n => {
  const shared = byFirst.get(n.split(' ')[0]).length > 1 ? ' ⚠ shared first name' : '';
  return `| ${n} | ${[...names.get(n)].join(', ')}${shared} |`;
});

fs.writeFileSync(OUT, `# Names already used

Generated by \`node tools/names_used.js\` — do not edit above "Story-only names"; re-run the script instead.
Before naming anyone new: check the first name here AND grep it as a whole word in both wikis (chronicle-only names are only listed if added below).

Rules: names from cultures all over the world · no shared first names · no look-alike starts (Lyra/Lyria, Maeve/Mael, Teo/Teodor) · Vorn Ashcaller is the only Vorn; only Mira Vorn and Mira Voss are Miras · never rename chapter names.

${names.size} names. ⚠ marks a first name used by more than one person (mostly canon families — leave them).

| Name | Where |
|---|---|
${rows.join('\n')}

## Story-only names${keep}`);
console.log(OUT, names.size, 'names');
